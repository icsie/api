CREATE OR REPLACE VIEW vd_subclass AS
SELECT p.cid as pcid, p.name as parent_name, c.cid as cid, c.name as child_name
FROM class p, inheritance i, class c
WHERE p.cid = i.pcid AND c.cid = i.ccid;
